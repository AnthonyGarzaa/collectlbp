"""Build vib/starfield.js: the Vib-Ribbon section's background star pattern.

Copies of the transparent poster starbursts (vib/Starbursts Transparent/) run
down both sides of the content box. Every star is measured from the box's
border, not the screen edge: each one sits at a fixed distance out from the
border, anywhere across the SPAN px strip beside the box that the Vibri
renders also use (its outer edge never past the strip), so a wider window or
zooming out never spreads the stars apart.

Each side gets its own fixed sequence of stars (file, inset, step, w, h):
vib.js walks it down the page from the bottom of the masthead in small
steps (shorter than the stars, so neighbours overlap in height and stagger
sideways), trying a few distances from the border for each star and dropping
it below any Vibri render or star it would touch. Varied steps and the odd
larger blank spot keep it scattered; the sequence repeats if a page is
taller than it.

Stars keep their native size, except the largest ones, which are scaled down
(aspect kept) so the longest side is at most MAX_SIDE.

The seed is fixed, so re-running produces the same pattern.
"""
import glob
import json
import os
import random

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = 'vib/Starbursts Transparent'
SRC = os.path.join(ROOT, *SRC_DIR.split('/'))
OUT = os.path.join(ROOT, 'vib', 'starfield.js')

LENGTH = 80          # stars per side before the sequence repeats
SPAN = 230           # strip beside the box: keep equal to STRIP in vib.js
STEP = (20, 75)      # how far down each star starts from the previous one, px
BLANK = 0.12         # chance of a larger blank spot instead of a normal step
BLANK_STEP = (170, 260)
MAX_SIDE = 80        # longest side of the biggest stars, px
SEED = 1999          # Vib-Ribbon's Japanese release year

rng = random.Random(SEED)
stars = []
for f in sorted(glob.glob(os.path.join(SRC, '*.png'))):
    w, h = Image.open(f).size
    k = min(1.0, MAX_SIDE / max(w, h))
    stars.append((os.path.basename(f), round(w * k), round(h * k)))


def column():
    """One side: [file, inset from the box border, step, w, h]."""
    out, pool = [], []
    while len(out) < LENGTH:
        if not pool:
            pool = list(range(len(stars)))
            rng.shuffle(pool)
        name, w, h = stars[pool.pop()]
        step = rng.randint(*BLANK_STEP) if rng.random() < BLANK else rng.randint(*STEP)
        out.append([name, rng.randint(0, SPAN - w), step, w, h])
    return out


data = {'span': SPAN, 'dir': SRC_DIR + '/', 'left': column(), 'right': column()}
with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
    fh.write('/* Generated by scripts/build_vib_starfield.py; do not edit by hand.\n'
             '   Per side of the content box, top to bottom (repeats):\n'
             '   [file, inset from the box border, step, w, h]. */\n')
    fh.write('window.VIB_STARFIELD = ')
    json.dump(data, fh, separators=(',', ':'))
    fh.write(';\n')
print('%d stars per side across a %dpx strip, max side %dpx -> %s'
      % (LENGTH, SPAN, max(max(p[3], p[4]) for p in data['left'] + data['right']),
         os.path.relpath(OUT, ROOT)))
